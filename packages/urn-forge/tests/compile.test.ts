import { spawnSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { main, type CliIo } from '../src/cli.js';
import { compile, DEFAULT_PLUGINS, generatedHeader } from '../src/engine.js';
import { GENERATOR_VERSION } from '../src/version.js';

const repo = (path: string) => fileURLToPath(new URL(`../${path}`, import.meta.url));
const read = (path: string) => readFile(path, 'utf8');

describe('compile engine', () => {
  let mathSource: string;
  beforeEach(async () => {
    mathSource = await read(repo('tests/fixtures/math/domain.manifest.yaml'));
  });

  it('keeps GENERATOR_VERSION equal to package.json', async () => {
    expect(JSON.parse(await read(repo('package.json'))).version).toBe(GENERATOR_VERSION);
  });

  it('emits both files sorted, each with the header above the plugin output', async () => {
    const result = compile(mathSource);
    expect(result.diagnostics).toEqual([]);
    expect(result.files.map((f) => f.relativePath)).toEqual([
      'domain.runtime.generated.ts',
      'domain.schemas.generated.ts',
    ]);
    expect(result.fingerprint).toMatch(/^sha256:[0-9a-f]{64}$/);
    const emitted = DEFAULT_PLUGINS.flatMap(({ plugin }) => plugin.emit(result.ir!, {}).artifacts);
    for (const file of result.files) {
      const body = emitted.find((a) => a.relativePath === file.relativePath)!.content;
      expect(file.content).toBe(`${generatedHeader(result.fingerprint!)}\n${body}`);
      expect(file.content.startsWith(`// @generated by urn-forge ${GENERATOR_VERSION} — do not edit\n`)).toBe(true);
      expect(file.content).not.toContain('\r');
      expect(file.content.endsWith('\n') && !file.content.endsWith('\n\n')).toBe(true);
    }
  });

  it('is deterministic, and the fingerprint tracks plugin versions', () => {
    expect(compile(mathSource)).toEqual(compile(mathSource));
    const bumped = DEFAULT_PLUGINS.map((entry, i) =>
      i === 0 ? { ...entry, plugin: { ...entry.plugin, version: '9.9.9' } } : entry,
    );
    expect(compile(mathSource, bumped).fingerprint).not.toBe(compile(mathSource).fingerprint);
  });

  it('returns diagnostics and no files for an invalid manifest', () => {
    const result = compile(mathSource.replace('ref: geometry.field.radius', 'ref: geometry.field.diameter'));
    expect(result.files).toEqual([]);
    expect(result.diagnostics).toEqual([
      expect.objectContaining({ severity: 'error', urn: 'urn:demo:math:geometry:entity:circle' }),
    ]);
  });

  it('rejects an invalid plugin config', () => {
    const plugins = [{ ...DEFAULT_PLUGINS[0]!, config: { unexpected: true } }];
    const result = compile(mathSource, plugins);
    expect(result.files).toEqual([]);
    expect(result.diagnostics).toEqual([expect.objectContaining({ message: expect.stringContaining('plugin valibot config') })]);
  });
});

describe('urn-forge compile (CLI)', () => {
  let dir: string;
  let out: string[];
  let err: string[];
  let io: CliIo;

  beforeEach(async () => {
    dir = await mkdtemp(join(tmpdir(), 'urn-forge-'));
    out = [];
    err = [];
    io = { cwd: dir, stdout: (l) => out.push(l), stderr: (l) => err.push(l) };
    await writeFile(join(dir, 'domain.manifest.yaml'), await read(repo('tests/fixtures/math/domain.manifest.yaml')));
  });
  afterEach(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  it('writes the generated files, and a second run changes nothing', async () => {
    expect(await main(['compile'], io)).toBe(0);
    expect(err).toEqual([]);
    expect(out.slice(0, 2)).toEqual([
      'wrote      src/generated/domain.runtime.generated.ts',
      'wrote      src/generated/domain.schemas.generated.ts',
    ]);
    const first = await read(join(dir, 'src/generated/domain.schemas.generated.ts'));

    out = [];
    expect(await main(['compile'], io)).toBe(0);
    expect(out.slice(0, 2)).toEqual([
      'unchanged  src/generated/domain.runtime.generated.ts',
      'unchanged  src/generated/domain.schemas.generated.ts',
    ]);
    expect(await read(join(dir, 'src/generated/domain.schemas.generated.ts'))).toBe(first);
  });

  it('honours --manifest and --out', async () => {
    expect(await main(['compile', '--manifest', 'domain.manifest.yaml', '--out', 'gen'], io)).toBe(0);
    expect(out[0]).toBe('wrote      gen/domain.runtime.generated.ts');
  });

  it('exits 1 with diagnostics for an invalid manifest and writes nothing', async () => {
    await writeFile(join(dir, 'bad.yaml'), 'manifest: { namespace: demo, domain: math, version: 0.1.0 }\ngeometry.field.radius: { primitive: decimal }\n');
    expect(await main(['compile', '--manifest', 'bad.yaml'], io)).toBe(1);
    expect(err).toEqual([
      'bad.yaml:2:37  error  unknown-primitive  geometry.field.radius.primitive: unknown primitive "decimal" (MVP primitives: float, integer, string)',
    ]);
    expect(out).toEqual([]);
  });

  it('exits 1 when the manifest is missing, and 2 on usage errors', async () => {
    expect(await main(['compile', '--manifest', 'nope.yaml'], io)).toBe(1);
    expect(err[0]).toMatch(/^nope\.yaml {2}error {2}manifest-unreadable {2}cannot read manifest/);
    expect(await main(['frobnicate'], io)).toBe(2);
    expect(await main(['compile', '--bogus'], io)).toBe(2);
  });
});

describe('bin/urn-forge.js', () => {
  it('runs the TypeScript CLI through tsx', () => {
    const run = spawnSync(process.execPath, [repo('bin/urn-forge.js'), '--version'], { encoding: 'utf8' });
    expect(run.stderr).toBe('');
    expect(run.stdout).toBe(`${GENERATOR_VERSION}\n`);
    expect(run.status).toBe(0);
  });
});
